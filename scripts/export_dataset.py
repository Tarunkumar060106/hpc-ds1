#!/usr/bin/env python3
"""
Export the HPC-DS1 benchmark dataset: every real run on every machine, one row
each, with the machine's hardware. Machine names are replaced by neutral ids
(e.g. "rtx4050-laptop") so no host names or user paths leave the lab.

Sources: hpc_ds1/data/real (this laptop) and every data/lab/<machine>/.hpc_ds1
folder copied back from the lab (the .hpc_ds1 folder of each PC, zipped).

    python scripts/export_dataset.py   -> dataset/hpc_ds1_runs.csv, dataset/machines.json, dataset/README.md
"""

import csv
import json
import sys
from collections import Counter
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from hpc_ds1.kernels import KERNELS  # noqa: E402
from hpc_ds1.paths import DATA_DIR  # noqa: E402

OUT = PROJECT_ROOT / "dataset"
FIELDS = ["machine", "workload", "size", "size_unit", "ranks", "threads", "gpu", "precision", "status",
          "runtime_sec", "gpu_peak_gb", "memory_gb", "cpu_util_pct", "gpu_busy_pct", "comm_overhead_pct",
          "noise_pct", "rel_error", "error", "measured_at"]


def machine_id(hw):
    gpu = (hw.get("gpu_model") or "cpu-only").replace("NVIDIA GeForce ", "").replace(" Laptop GPU", "-laptop")
    return gpu.lower().replace(" ", "")


def sources():
    yield DATA_DIR
    for d in sorted((PROJECT_ROOT / "data" / "lab").glob("*/.hpc_ds1/data")):
        yield d


def status(r):
    if r.get("skipped"):
        return "skipped"
    if not r.get("ok"):
        return "out_of_memory" if r.get("oom") else "failed"
    return "ok" if r.get("correct") else "wrong_result"


def main():
    OUT.mkdir(exist_ok=True)
    machines, rows, seen = {}, [], set()
    for src in sources():
        hw = json.loads((src / "hardware.json").read_text())
        mid = machine_id(hw)
        if hw.get("name") in seen:  # the same machine copied twice
            continue
        seen.add(hw.get("name"))
        machines[mid] = {k: hw.get(k) for k in ("cpu_model", "cpu_cores", "cpu_threads", "cpu_freq_ghz", "ram_gb",
                                                "gpu_model", "gpu_memory_gb")}
        for line in (src / "measurements.jsonl").read_text().splitlines():
            if not line.strip():
                continue
            r = json.loads(line)
            t = r.get("telemetry") or {}
            c = r["config"]
            k = KERNELS.get(r["workload"])
            rows.append({"machine": mid, "workload": r["workload"], "size": r["size"],
                         "size_unit": k.size_unit if k else "", "ranks": c["ranks"], "threads": c["threads"],
                         "gpu": int(bool(c["gpu"])), "precision": c["precision"], "status": status(r),
                         "runtime_sec": t.get("runtime_sec"), "gpu_peak_gb": t.get("gpu_peak_gb"),
                         "memory_gb": t.get("memory_gb"), "cpu_util_pct": t.get("cpu_util_pct"),
                         "gpu_busy_pct": t.get("gpu_busy_pct"), "comm_overhead_pct": t.get("comm_overhead_pct"),
                         "noise_pct": t.get("noise_pct"), "rel_error": r.get("rel_error"),
                         "error": (r.get("error") or "")[:160], "measured_at": r.get("measured_at")})
    with open(OUT / "hpc_ds1_runs.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, FIELDS)
        w.writeheader()
        w.writerows(rows)
    (OUT / "machines.json").write_text(json.dumps(machines, indent=2))

    by = Counter((r["machine"], r["status"]) for r in rows)
    lines = ["# HPC-DS1 benchmark dataset", "",
             "Every row is one real run of one workload, at one size, with one setting (processes, threads, CPU or GPU, "
             "fp32 or bf16), on one machine. Nothing is simulated. Generated by `scripts/export_dataset.py`.", "",
             "| Machine | CPU | GPU | Runs | OK | Out of memory | Failed / wrong | Skipped |", "|---|---|---|---|---|---|---|---|"]
    for mid, hw in machines.items():
        n = sum(v for (m, _), v in by.items() if m == mid)
        lines.append(f"| {mid} | {hw['cpu_cores']} cores, {hw['ram_gb']} GB | {hw['gpu_model']} ({hw['gpu_memory_gb']} GB) | {n} | "
                     f"{by[(mid, 'ok')]} | {by[(mid, 'out_of_memory')]} | {by[(mid, 'failed')] + by[(mid, 'wrong_result')]} | "
                     f"{by[(mid, 'skipped')]} |")
    lines += ["", "## Workloads", "", "| Workload | What it is | Size means |", "|---|---|---|"]
    for name, k in KERNELS.items():
        lines.append(f"| `{name}` | {k.display_name} | {k.size_unit} |")
    lines += ["", "## Columns", "",
              "- `status`: `ok` (ran, result matches the fp32 reference), `wrong_result` (ran, but the answer differs "
              "beyond the workload's tolerance), `out_of_memory`, `failed` (any other error, e.g. no GPU version), "
              "`skipped` (not run: a CPU setting of a GPU-class workload expected to exceed a 60 s budget, from a real "
              "all-cores run, or a run that would not fit in free RAM; the reason is in `error`).",
              "- `runtime_sec`: median wall time of the repeats; `gpu_peak_gb`: real peak GPU memory (above the card's "
              "memory, Windows spills into system RAM, so it can exceed it); `memory_gb`: host RSS of all processes plus GPU peak.",
              "- `rel_error`: relative error of the result against the fp32 reference.",
              "- Machine hardware is in `machines.json`."]
    (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} runs from {len(machines)} machines -> {OUT}")
    for mid in machines:
        print(" ", mid, {s: by[(mid, s)] for s in ("ok", "out_of_memory", "failed", "wrong_result", "skipped")})


if __name__ == "__main__":
    main()
